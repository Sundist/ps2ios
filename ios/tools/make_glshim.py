#!/usr/bin/env python3
"""Make the desktop-GL shim for iOS builds.

SDL3's SDL_opengl.h is empty on iOS ("No OpenGL on iOS"), but psxrecomp's
OpenGL backend (gpu_gl_renderer.c) is always compiled. On iOS that backend is
never used: the game.toml written by ps1ios selects the software or Vulkan
renderer, and SDL cannot make a desktop GL context there anyway. So the build
only needs the GL declarations and link-time bodies:

  glshim/SDL3/SDL_opengl.h  SDL's header with the iOS guard removed
  glshim/gl_stubs.c         a body for every GL 1.x function it declares,
                            returning 0 (never reached at run time)

  python3 ios/tools/make_glshim.py <SDL3 source>/include/SDL3/SDL_opengl.h
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(sys.argv[1], encoding="utf-8").read()

guard_open = "#ifndef SDL_PLATFORM_IOS  /* No OpenGL on iOS. */\n"
guard_close = "#endif /* !SDL_PLATFORM_IOS */\n"
assert src.count(guard_open) == 1 and src.count(guard_close) == 1, "SDL_opengl.h layout changed"
hdr = src.replace(guard_open, "/* ps1ios: iOS guard removed, see ios/tools/make_glshim.py */\n", 1)
hdr = hdr.replace(guard_close, "", 1)
out_h = os.path.join(HERE, "glshim", "SDL3", "SDL_opengl.h")
os.makedirs(os.path.dirname(out_h), exist_ok=True)
with open(out_h, "w", encoding="utf-8") as f:
    f.write(hdr)

decls = re.findall(r"^GLAPI\s+(.+?)\s+GLAPIENTRY\s+(gl\w+)\s*\((.*?)\)\s*;", src, re.M | re.S)
seen, bodies = set(), []
for ret, name, params in decls:
    if name in seen:
        continue
    seen.add(name)
    ret = " ".join(ret.split())
    params = " ".join(params.split()) or "void"
    if ret == "void":
        body = "{}"
    elif "*" in ret:
        body = "{ return 0; }"
    else:
        body = "{ return (%s)0; }" % ret
    bodies.append(f"{ret} GLAPIENTRY {name}({params}) {body}")

with open(os.path.join(HERE, "glshim", "gl_stubs.c"), "w", encoding="utf-8") as f:
    f.write("/* Generated by ios/tools/make_glshim.py: link-time bodies for the desktop GL 1.x\n"
            " * functions psxrecomp's OpenGL backend calls directly. iOS has no desktop GL;\n"
            " * that backend never runs there, so none of these is reached. */\n"
            "#include <SDL3/SDL_opengl.h>\n\n"
            "#if defined(__clang__)\n#pragma clang diagnostic ignored \"-Wunused-parameter\"\n#endif\n\n")
    f.write("\n".join(bodies) + "\n")
print(f"{out_h}: guard removed; gl_stubs.c: {len(bodies)} functions")
